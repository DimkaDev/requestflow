-- V1__init_schema.sql
-- FlowTrace Schema (spec section 8)

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    external_id VARCHAR(128) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    id UUID PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(128) NOT NULL,
    auto_discover BOOLEAN NOT NULL DEFAULT TRUE,
    retention_days INT NOT NULL DEFAULT 7,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_projects_owner ON projects(owner_id);

CREATE TABLE IF NOT EXISTS api_keys (
    id UUID PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(128) NOT NULL,
    key_prefix VARCHAR(32) NOT NULL,
    key_hash VARCHAR(64) NOT NULL UNIQUE,
    rate_limit_per_s INT NOT NULL DEFAULT 1000,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_api_keys_project ON api_keys(project_id);
CREATE INDEX IF NOT EXISTS idx_api_keys_hash ON api_keys(key_hash);

CREATE TABLE IF NOT EXISTS diagrams (
    id UUID PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    version INT NOT NULL,
    graph TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(project_id, version)
);

CREATE INDEX IF NOT EXISTS idx_diagrams_project_version ON diagrams(project_id, version DESC);

CREATE TABLE IF NOT EXISTS traces (
    id VARCHAR(36) NOT NULL,
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_event_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(16) NOT NULL DEFAULT 'ok',
    event_count INT NOT NULL DEFAULT 0,
    last_node VARCHAR(64),
    PRIMARY KEY (project_id, id)
);

CREATE INDEX IF NOT EXISTS idx_traces_project_last_event ON traces(project_id, last_event_at DESC);

CREATE TABLE IF NOT EXISTS trace_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    trace_id VARCHAR(36) NOT NULL,
    branch VARCHAR(64) NOT NULL DEFAULT 'main',
    from_node VARCHAR(64),
    node VARCHAR(64) NOT NULL,
    type VARCHAR(16) NOT NULL DEFAULT 'enter',
    label VARCHAR(64),
    attrs TEXT,
    client_ts BIGINT,
    server_ts TIMESTAMP WITH TIME ZONE NOT NULL,
    seq BIGINT
);

CREATE INDEX IF NOT EXISTS idx_trace_events_lookup ON trace_events(project_id, trace_id, server_ts ASC);
CREATE INDEX IF NOT EXISTS idx_trace_events_server_ts ON trace_events(project_id, server_ts DESC);
